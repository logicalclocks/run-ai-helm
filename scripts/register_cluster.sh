#!/usr/bin/env bash
#
# Registers a Kubernetes cluster in a running Run:ai control plane and writes the values the
# cluster profile (values.cluster.yaml) needs: controlPlane.url, controlPlane.bootstrapToken,
# cluster.uid and cluster.url.
#
# Idempotent: an existing cluster with the same name is reused. The bootstrap token is single
# use, so every run mints a new one; run this before each install or upgrade of the cluster release.
#
# Same API calls as runai-installer (internal/orchestrator2/actions/ensure_cluster.go and
# control_plane_ref.go).
#
# Usage:
#   scripts/register_cluster.sh --domain runai.example.com [--cluster-name runai-cluster]
#       [--cluster-url https://runai.example.com] [--admin-user test@run.ai]
#       [--admin-password <pw>] [--version 3.0.20] [--cacert ca.pem | --insecure]
#       [--output cluster-registration.yaml]
#
# Without --admin-password the password is read from Secret runai-backend-gen-tenants-manager in
# namespace runai-backend, which needs kubectl access to the control-plane cluster.
# Requires curl and jq.

set -euo pipefail

DOMAIN=""
CLUSTER_NAME="runai-cluster"
CLUSTER_URL=""
ADMIN_USER="test@run.ai"
ADMIN_PASSWORD="${RUNAI_ADMIN_PASSWORD:-}"
VERSION="$(sed -n 's/^appVersion: *"\{0,1\}\([^"]*\)"\{0,1\}$/\1/p' "$(dirname "$0")/../charts/cluster/Chart.yaml")"
OUTPUT="cluster-registration.yaml"
CURL_TLS=()
TIMEOUT_SECONDS=900

usage() { sed -n '3,22p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo ">> $*" >&2; }

while [[ $# -gt 0 ]]; do
    case "$1" in
        --domain) DOMAIN="$2"; shift 2 ;;
        --cluster-name) CLUSTER_NAME="$2"; shift 2 ;;
        --cluster-url) CLUSTER_URL="$2"; shift 2 ;;
        --admin-user) ADMIN_USER="$2"; shift 2 ;;
        --admin-password) ADMIN_PASSWORD="$2"; shift 2 ;;
        --version) VERSION="$2"; shift 2 ;;
        --cacert) CURL_TLS=(--cacert "$2"); shift 2 ;;
        --insecure) CURL_TLS=(--insecure); shift ;;
        --output) OUTPUT="$2"; shift 2 ;;
        --timeout) TIMEOUT_SECONDS="$2"; shift 2 ;;
        -h|--help) usage ;;
        *) echo "unknown argument: $1" >&2; usage 1 ;;
    esac
done

[[ -n "$DOMAIN" ]] || die "--domain is required"
command -v jq >/dev/null || die "jq is required"
CP_URL="https://${DOMAIN#https://}"
CLUSTER_URL="${CLUSTER_URL:-$CP_URL}"

if [[ -z "$ADMIN_PASSWORD" ]]; then
    ADMIN_PASSWORD="$(kubectl get secret runai-backend-gen-tenants-manager -n runai-backend \
        -o jsonpath='{.data.ADMIN_PASSWORD}' | base64 --decode)" \
        || die "could not read ADMIN_PASSWORD from secret runai-backend-gen-tenants-manager; pass --admin-password"
fi

api() {
    curl --silent --show-error --fail --max-time 60 "${CURL_TLS[@]}" \
        -H 'Accept: application/json' "$@"
}

get_token() {
    api -X POST "$CP_URL/api/v1/token" -H 'Content-Type: application/json' \
        -d "$(jq -n --arg u "$ADMIN_USER" --arg p "$ADMIN_PASSWORD" \
            '{grantType: "password", username: $u, password: $p}')" \
        | jq -er '.accessToken'
}

# Retry until the deadline: the tenant realm and the backend services come up asynchronously after
# the control-plane release reports ready.
retry() {
    local what="$1"; shift
    local deadline=$((SECONDS + TIMEOUT_SECONDS))
    local out
    until out="$("$@" 2>/dev/null)" && [[ -n "$out" ]]; do
        (( SECONDS < deadline )) || die "timed out after ${TIMEOUT_SECONDS}s waiting for: $what"
        log "waiting for $what..."
        sleep 10
    done
    printf '%s' "$out"
}

log "Authenticating to $CP_URL as $ADMIN_USER"
TOKEN="$(retry "control-plane login" get_token)"

find_cluster() {
    api -H "Authorization: Bearer $TOKEN" "$CP_URL/api/v1/clusters" \
        | jq -r --arg n "$CLUSTER_NAME" '[.[] | select(.name == $n)][0].uuid // empty'
}

create_cluster() {
    api -X POST "$CP_URL/api/v1/clusters" -H "Authorization: Bearer $TOKEN" \
        -H 'Content-Type: application/json' \
        -d "$(jq -n --arg n "$CLUSTER_NAME" --arg d "$CLUSTER_URL" '{name: $n, domain: $d}')" \
        | jq -er '.uuid'
}

CLUSTER_UID="$(find_cluster || true)"
if [[ -n "$CLUSTER_UID" ]]; then
    log "Cluster $CLUSTER_NAME already registered: $CLUSTER_UID"
else
    CLUSTER_UID="$(retry "cluster registration" create_cluster)"
    log "Registered cluster $CLUSTER_NAME: $CLUSTER_UID"
fi

install_info() {
    api -G "$CP_URL/api/v1/clusters/$CLUSTER_UID/cluster-install-info" \
        -H "Authorization: Bearer $TOKEN" \
        --data-urlencode "version=$VERSION" \
        --data-urlencode "remoteClusterUrl=$CLUSTER_URL" \
        | jq -er '.bootstrapToken // empty'
}
BOOTSTRAP_TOKEN="$(retry "installer bootstrap token" install_info)"

umask 077
cat > "$OUTPUT" <<EOF
# Generated by scripts/register_cluster.sh for cluster $CLUSTER_NAME. Contains a single-use
# bootstrap token: regenerate before each install or upgrade, and do not commit it.
cluster:
  runai-cluster:
    controlPlane:
      url: "$CP_URL"
      bootstrapToken: "$BOOTSTRAP_TOKEN"
    cluster:
      uid: "$CLUSTER_UID"
      url: "$CLUSTER_URL"
EOF
log "Wrote $OUTPUT"
